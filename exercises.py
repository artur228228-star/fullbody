ALL: Dict[str, Exercise] = {e.key: e for lst in EXERCISES.values() for e in lst}


def main_pair(group: str) -> List[Exercise]:
    """Два основных упражнения на группу."""
    return EXERCISES[group][:2]


def alternatives(group: str, exclude: str) -> List[Exercise]:
    return [e for e in EXERCISES[group] if e.key != exclude]


def build_plan(mode: str = "full", groups: List[str] | None = None) -> List[Exercise]:
    """
    full    — фуллбади: все группы × 2 упражнения (16 упражнений).
    express — быстрая: все группы × 1 упражнение (8 упражнений, ~35 минут).
    """
    plan: List[Exercise] = []
    for g in groups or list(GROUPS):
        pair = main_pair(g)
        plan.extend(pair if mode == "full" else pair[:1])
    return plan
